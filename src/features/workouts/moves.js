export function moveHint(title) {
  const key = String(title || "").trim();
  return HINTS[key] || "Повторяй движение ровно до конца таймера. Без рывков, дыши.";
}

export function uniqueMoveTitles(session) {
  const seen = new Set();
  const list = [];
  for (const move of session?.moves || []) {
    const title = String(move?.title || "").trim();
    if (!title || seen.has(title)) {
      continue;
    }
    seen.add(title);
    list.push(title);
  }
  return list;
}
